// Screen Trainer — builds src/data-breed.js: what breeding needs to know about each species.
//   node tools/build-breed-data.js <folder with the PokeAPI CSV tables>
// Reads pokemon_egg_groups.csv and pokemon_species.csv (https://github.com/PokeAPI/pokeapi, data/v2/csv) and writes,
// for every species the game knows: its egg groups, its hatch counter (egg cycles), what it evolves from, and whether
// it is a baby. It also checks the gender rates in src/data.js against the table and says so.
'use strict';
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-breed-data.js <csv folder>'); process.exit(1); }
const csv = (name) => fs.readFileSync(path.join(dir, name), 'utf8').trim().split(/\r?\n/).map((l) => l.split(','));
const DATA = new Function(fs.readFileSync(path.join(__dirname, '..', 'src', 'data.js'), 'utf8') + ';return DATA;')();
const GROUPS = ['', 'monster', 'water1', 'bug', 'flying', 'ground', 'fairy', 'plant', 'humanshape', 'water3', 'mineral', 'indeterminate', 'water2', 'ditto', 'dragon', 'no-eggs'];
const max = Math.max(...Object.keys(DATA.dex).map(Number));
const g = Array.from({ length: max + 1 }, () => []), h = new Array(max + 1).fill(0), from = new Array(max + 1).fill(0), baby = [];
for (const [sp, grp] of csv('pokemon_egg_groups.csv').slice(1)) if (DATA.dex[sp]) g[+sp].push(+grp);
const sp = csv('pokemon_species.csv'), head = sp[0], col = (n) => head.indexOf(n);
let wrong = 0;
for (const r of sp.slice(1)) {
  const id = +r[0];
  if (!DATA.dex[id]) continue;
  h[id] = +r[col('hatch_counter')] || 20; from[id] = +r[col('evolves_from_species_id')] || 0;
  if (r[col('is_baby')] === '1') baby.push(id);
  if (DATA.dex[id].gn !== +r[col('gender_rate')]) { wrong++; console.log(`gender rate differs for ${id} ${DATA.dex[id].n}: game ${DATA.dex[id].gn}, table ${r[col('gender_rate')]}`); }
}
const out = `// Screen Trainer — generated by tools/build-breed-data.js from the PokeAPI CSV tables. Do not edit by hand.\n// groups: the names of the egg groups. g[species]: its egg groups. h[species]: hatch counter (egg cycles).\n// from[species]: what it evolves from (0 = nothing). baby: the baby species.\nconst BREED_DATA = ${JSON.stringify({ groups: GROUPS, g, h, from, baby })};\nif (typeof module !== 'undefined') module.exports = BREED_DATA;\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data-breed.js'), out);
console.log(`src/data-breed.js written: ${max} species, ${baby.length} babies, ${out.length} bytes. Gender rates that differ from the table: ${wrong}.`);
