#!/usr/bin/env node
// Screen Trainer — builds src/data-extra.js from the public PokeAPI CSV tables
// (https://github.com/PokeAPI/pokeapi, folder data/v2/csv). Only needed when that data changes.
//
//   node tools/build-extra-data.js <path to data/v2/csv> [<path to sprites folder>]
//
// Output: item names, which items evolve which species, the items wild species carry, and the
// category / height / weight line shown in the Pokédex.
'use strict';
const fs = require('fs');
const path = require('path');
const dir = process.argv[2], sprites = process.argv[3];
if (!dir) { console.error('usage: node tools/build-extra-data.js <pokeapi csv folder> [sprites folder]'); process.exit(2); }
const csv = (name) => {
  const [head, ...rows] = fs.readFileSync(path.join(dir, name + '.csv'), 'utf8').trim().split(/\r?\n/);
  const cols = head.split(',');
  return rows.map((r) => { const out = {}, v = []; let cur = '', q = false; for (const ch of r) { if (ch === '"') q = !q; else if (ch === ',' && !q) { v.push(cur); cur = ''; } else cur += ch; } v.push(cur); cols.forEach((c, i) => { out[c] = v[i]; }); return out; });
};
const items = csv('items'), itemKey = {}, itemName = {};
for (const it of items) itemKey[it.id] = it.identifier;
for (const n of csv('item_names')) if (n.local_language_id === '9') itemName[itemKey[n.item_id]] = n.name;
const have = sprites ? new Set(fs.readdirSync(path.join(sprites, 'items')).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4))) : null;
const ok = (k) => !!k && (!have || have.has(k));

const species = csv('pokemon_species'), from = {};
for (const s of species) if (s.evolves_from_species_id) from[s.id] = +s.evolves_from_species_id;

// items that evolve a species when used on it (stones, and the items the games need a trade for)
const evo = {};
for (const e of csv('pokemon_evolution')) {
  const key = itemKey[e.trigger_item_id] || itemKey[e.held_item_id], to = +e.evolved_species_id, src = from[to];
  if (!key || !src || to > 1025 || !ok(key)) continue;
  if (e.region_id || e.evolved_pokemon_form_id || e.required_pokemon_form_id) continue;      // regional forms are not in the game
  const list = (evo[key] = evo[key] || []);
  if (list.some((x) => x[0] === src && x[1] === to)) continue;
  const row = [src, to];
  if (e.gender_id) row.push(e.gender_id === '1' ? 'f' : 'm');
  list.push(row);
}

// items wild species carry: [item, percent], from the most recent game that lists the species
const held = {}, latest = {};
for (const r of csv('pokemon_items')) {
  const id = +r.pokemon_id, v = +r.version_id, key = itemKey[r.item_id];
  if (id > 1025 || !ok(key)) continue;
  if (!(id in latest) || v > latest[id]) { latest[id] = v; held[id] = []; }
  if (v === latest[id] && !held[id].some((x) => x[0] === key)) held[id].push([key, +r.rarity]);
}

const genus = {};
for (const n of csv('pokemon_species_names')) if (n.local_language_id === '9') genus[n.pokemon_species_id] = n.genus.replace(/ Pok[eé]mon$/, '');
const dex = {};
for (const p of csv('pokemon')) if (+p.id <= 1025 && p.is_default === '1') dex[p.id] = [genus[p.species_id] || '', +p.height, +p.weight];

const used = new Set([...Object.keys(evo), ...Object.values(held).flat().map((x) => x[0])]);
const names = {};
for (const k of Object.keys(itemName)) if (ok(k)) names[k] = itemName[k];
const out = `// Generated by tools/build-extra-data.js from the public PokeAPI data set. Do not edit by hand.\nconst DATA_EXTRA = ${JSON.stringify({ itemNames: names, itemEvo: evo, wildItems: held, dex })};\nif (typeof module !== 'undefined') module.exports = DATA_EXTRA;\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data-extra.js'), out);
console.log(`items named: ${Object.keys(names).length}, evolution items: ${Object.keys(evo).length}, species with wild items: ${Object.keys(held).length}, dex lines: ${Object.keys(dex).length}, bytes: ${out.length}, referenced items: ${used.size}`);
