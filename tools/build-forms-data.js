// Screen Trainer — builds src/data-forms.js: Mega Evolutions, Primal forms and Gigantamax forms.
//   node tools/build-forms-data.js <folder with the PokeAPI CSV tables>
// Reads pokemon.csv, pokemon_stats.csv and pokemon_types.csv. For each species the game knows it lists its Mega (or
// Primal) forms with their own name, base stats and types, and the id of its Gigantamax form. The ids are the ones the
// sprite sets use for their file names (10034.png is Mega Charizard X).
'use strict';
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-forms-data.js <csv folder>'); process.exit(1); }
const csv = (name) => fs.readFileSync(path.join(dir, name), 'utf8').trim().split(/\r?\n/).slice(1).map((l) => l.split(','));
const DATA = new Function(fs.readFileSync(path.join(__dirname, '..', 'src', 'data.js'), 'utf8') + ';return DATA;')();
const stats = {}, types = {};
for (const [id, stat, base] of csv('pokemon_stats.csv')) if (+stat >= 1 && +stat <= 6) (stats[id] = stats[id] || [])[+stat - 1] = +base;
for (const [id, type, slot] of csv('pokemon_types.csv')) (types[id] = types[id] || [])[+slot - 1] = +type;
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const mega = {}, gmax = {};
let n = 0;
for (const [id, ident, sp] of csv('pokemon.csv')) {
  if (+id < 10000 || !DATA.dex[sp]) continue;
  const base = DATA.dex[sp].n, m = /-(mega|primal)(?:-([xyz]))?$/.exec(ident);
  if (/-gmax$/.test(ident)) { if (!gmax[sp]) gmax[sp] = +id; continue; }      // (the first one: Urshifu and Toxtricity have two that look alike here)
  if (!m || !stats[id] || !types[id]) continue;
  (mega[sp] = mega[sp] || []).push({ id: +id, n: `${cap(m[1])} ${base}${m[2] ? ' ' + m[2].toUpperCase() : ''}`, s: stats[id], t: types[id].filter(Boolean) });
  n++;
}
const out = `// Screen Trainer — generated by tools/build-forms-data.js from the PokeAPI CSV tables. Do not edit by hand.\n// mega[species]: its Mega Evolutions and Primal forms: { id (also the sprite's file name), n: name, s: base stats, t: type ids }.\n// gmax[species]: the id of its Gigantamax form.\nconst FORM_DATA = ${JSON.stringify({ mega, gmax })};\nif (typeof module !== 'undefined') module.exports = FORM_DATA;\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data-forms.js'), out);
console.log(`src/data-forms.js written: ${n} Mega and Primal forms of ${Object.keys(mega).length} species, ${Object.keys(gmax).length} Gigantamax forms, ${out.length} bytes.`);
